const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('yy', {
  list: () => ipcRenderer.invoke('profiles:list'),
  create: (name, color, extra) => ipcRenderer.invoke('profiles:create', name, color, extra),
  update: (id, patch) => ipcRenderer.invoke('profiles:update', id, patch),
  reorder: (ids) => ipcRenderer.invoke('profiles:reorder', ids),
  renameMany: (list) => ipcRenderer.invoke('profiles:renameMany', list),
  open: (id) => ipcRenderer.invoke('profiles:open', id),
  openMany: (ids) => ipcRenderer.invoke('profiles:openMany', ids),
  closeWin: (ids) => ipcRenderer.invoke('profiles:closeWin', ids),
  tile: () => ipcRenderer.invoke('windows:tile'),
  openAllBg: () => ipcRenderer.invoke('profiles:openAllBg'),
  fullscreenAll: () => ipcRenderer.invoke('windows:fullscreenAll'),
  fsState: () => ipcRenderer.invoke('windows:fsState'),
  batchOpen: (opts) => ipcRenderer.invoke('batch:open', opts),
  clear: (id) => ipcRenderer.invoke('profiles:clear', id),
  remove: (id) => ipcRenderer.invoke('profiles:delete', id),
  info: () => ipcRenderer.invoke('app:info'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),
  onChange: (cb) => ipcRenderer.on('profiles-changed', (_e, list) => cb(list)),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  onOpenSettings: (cb) => ipcRenderer.on('open-settings', () => cb()),
  onOpenEdit: (cb) => ipcRenderer.on('open-edit', (_e, id) => cb(id)),
  onOpenBatch: (cb) => ipcRenderer.on('open-batch', (_e, b) => cb(b)),
  platform: process.platform,
});
