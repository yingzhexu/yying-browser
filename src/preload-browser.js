  newTab: call('tab:new'),
  closeTab: call('tab:close'),
  switchTab: call('tab:switch'),
  moveTab: call('tab:move'),
  tabMenu: call('tab:menu'),
  toggleMute: call('tab:mute'),
  go: call('nav:go'),
  back: call('nav:back'),
  forward: call('nav:forward'),
  reload: call('nav:reload'),
  stop: call('nav:stop'),
  goNewtab: call('nav:newtab'),
  zoomReset: call('zoom:reset'),
  setPanel: call('panel:set'),
  mainMenu: call('menu:main'),
  suggest: call('suggest:query'),
  showSuggest: call('suggest:show'),
  hideSuggest: call('suggest:hide'),
  history: call('history:get'),
  deleteHistory: call('history:delete'),
  clearHistory: call('history:clear'),
  clearCookies: call('cookies:clear'),
  clearData: call('data:clear'),
  toggleBookmark: call('bookmark:toggle'),
  removeBookmark: call('bookmark:remove'),
  bookmarkMenu: call('bookmark:menu'),
  downloadAction: call('download:action'),
  clearDownloads: call('download:clear'),
  openDownloadFolder: call('download:folder'),
  showHome: call('home:show'),
  introDone: call('intro:done'),
  profileMenu: call('menu:profiles'),
  switchProfile: call('profile:switch'),
